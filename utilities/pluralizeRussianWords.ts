/**
 * Универсальная функция склонения русских слов по целому числу.
 *
 * Формы передаются строго в таком порядке:
 * 1) Именительный падеж, ед. число — форма для чисел ...1 (кроме 11)
 *    Примеры словоформ: "день", "комментарий", "товар"
 * 2) Родительный падеж, ед. число — форма для чисел ...2–4 (кроме 12–14)
 *    Примеры словоформ: "дня", "комментария", "товара"
 * 3) Родительный падеж, мн. число — форма для 0, 5–20, ...11–19, ...0, ...5–9
 *    Примеры словоформ: "дней", "комментариев", "товаров"
 *
 * Ожидаемые аргументы:
 * - count: целое число (может быть отрицательным). Диапазон: от -∞ до +∞.
 * - forms: кортеж из 3 строк в порядке [Именительный ед.ч., Родительный ед.ч., Родительный мн.ч.].
 *
 * Правила выбора формы (по абсолютному значению числа):
 * - 11–19 → Родительный мн.ч. (forms[2])
 * - ...1 → Именительный ед.ч. (forms[0])
 * - ...2–4 → Родительный ед.ч. (forms[1])
 * - остальное → Родительный мн.ч. (forms[2])
 *
 * Примеры:
 * - 0 → "дней", "товаров", "комментариев"
 * - 1 → "день", "товар", "комментарий"
 * - 2 → "дня", "товар", "комментарий"
 * - 5 → "дней", "товаров", "комментариев"
 * - 11 → "дней", "товаров", "комментариев"
 * - 21 → "день", "товар", "комментарий"
 * - 22 → "дня", "товар", "комментарий"
 * - 25 → "дней", "товаров", "комментариев"
 * - -1 → "день", -2 → "дня", -11 → "дней"
 */

export type RuWordForms = [string, string, string];

/**
 * Возвращает ТОЛЬКО слово в корректной форме.
 * forms: [Именительный ед.ч., Родительный ед.ч., Родительный мн.ч.]
 * Пример набора форм: ["день", "дня", "дней"]
 */
export function pluralizeRu(count: number, forms: RuWordForms): string {
  const n = Math.abs(count) % 100;
  const n1 = n % 10;

  if (n > 10 && n < 20) return forms[2];
  if (n1 === 1) return forms[0];
  if (n1 >= 2 && n1 <= 4) return forms[1];

  return forms[2];
}
