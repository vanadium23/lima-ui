export enum IconSize {
  Small = "small",
  Medium = "medium",
  Large = "large",
}

type IconProps = {
  name: IconName;
  size?: IconSize;
};

export const Icon: Component<IconProps> = (props) => {
  const mProps: Required<IconProps> = mergeProps(
    {
      size: IconSize.Medium,
    },
    props,
  );
  return (
    <Dynamic
      component={icons[props.name]}
      size={mProps.size}
      ariaHidden={true}
    />
  );
};
